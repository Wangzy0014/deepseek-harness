def write_csv(name: str, header, rows):
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    with open(FIXTURE_DIR / name, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        writer.writerows(rows)


